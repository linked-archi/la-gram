/**
 * The provenance of edits (Req 9.16; meta's DD-27, *What a modeller records of its edits*): who changed a
 * concept, when and with which la-gram, stamped inside the edit — so undo takes it back — and kept minimal:
 * four statements a concept, five an activity, la-gram and each user once.
 */
import { describe, it, expect, beforeEach } from 'vitest';
import { DataFactory } from 'n3';
import type { NamedNode, Quad } from '@rdfjs/types';
import { createApp, type App } from '../../app.js';
import type { ObservableRdfStore } from '../../rdf-engine/observable-store.js';
import { EditProvenance, LA_GRAM_HOME, modellerIri, provenanceOf, type Editor } from '../provenance.js';
import { settleEditProvenance } from '../model-merge.js';
import { snapshotOf } from '../version-history.js';
import { keyDigest } from '../short-hash.js';
import { NAMESPACES } from '../../rdf-engine/namespaces.js';

const { namedNode, literal, quad, defaultGraph } = DataFactory;
const nn = (iri: string) => namedNode(iri) as unknown as NamedNode;
const AM4 = 'https://meta.linked.archi/archimate4/onto#';
const PROV = NAMESPACES.prov;
const DCT = NAMESPACES.dcterms;
const SCHEMA = 'https://schema.org/';
const RDF_TYPE = NAMESPACES.rdf + 'type';

let app: App;
let store: ObservableRdfStore;
let clock: number;
let ids: number;
let editor: Editor | undefined;
let provenance: EditProvenance;

const values = (s: string, p: string) =>
  store.getQuads(nn(s), nn(p), null, defaultGraph() as never).map((q) => q.object.value).sort();
const one = (s: string, p: string) => values(s, p)[0];
/** As the store holds an `xsd:dateTime`: without the milliseconds when there are none. */
const time = (seconds: number) => new Date(Date.UTC(2026, 10, 20, 16, 0, seconds)).toISOString().replace('.000Z', 'Z');
const tick = (seconds = 1) => (clock += seconds * 1000);

async function freshApp(): Promise<void> {
  app = await createApp({ assetMode: 'offline', validationDelayMs: 1e9 });
  store = app.components.store as ObservableRdfStore;
  clock = Date.UTC(2026, 10, 20, 16, 0, 0);
  ids = 0;
  editor = { name: 'Ada' };
  provenance = new EditProvenance(store, {
    modelIri: () => app.session.modelIri,
    namespace: () => app.session.namespace()?.namespace,
    editor: () => editor,
    version: '9.9.9',
    now: () => new Date(clock),
    uuid: () => `activity-${++ids}`,
  });
  store.setStamper((diff) => provenance.stamp(diff));
}

describe('the provenance of edits', () => {
  beforeEach(async () => {
    await freshApp();
    app.newModel('Shop');
  }, 60_000);

  it('a concept made: created and modified, generated by the editing activity — la-gram 9.9.9 and Ada — at that time', () => {
    const ns = app.session.namespace()!.namespace;
    const model = app.session.modelIri!;
    tick(5);
    const shop = app.components.elementManager.createElement(`${AM4}ApplicationComponent`, model, { label: 'Web shop' }).value;
    const activity = `${ns}provenance/edit-activity-1`;
    const ada = `${ns}provenance/user-${keyDigest('Ada')}`;
    const agent = `${LA_GRAM_HOME}v9.9.9`;

    // On the concept: when, as Dublin Core says it.
    expect([one(shop, DCT + 'created'), one(shop, DCT + 'modified')]).toEqual([time(5), time(5)]);
    // In the provenance: which activity, and when.
    expect([one(shop, PROV + 'wasGeneratedBy'), one(shop, PROV + 'generatedAtTime')]).toEqual([activity, time(5)]);
    // The model changed too, in the same activity.
    expect([one(model, DCT + 'modified'), one(model, PROV + 'wasGeneratedBy')]).toEqual([time(5), activity]);
    // The activity: its times, la-gram and the user.
    expect(values(activity, RDF_TYPE)).toEqual([PROV + 'Activity']);
    expect([one(activity, PROV + 'startedAtTime'), one(activity, PROV + 'endedAtTime')]).toEqual([time(5), time(5)]);
    expect(values(activity, PROV + 'wasAssociatedWith')).toEqual([agent, ada].sort());
    expect(values(agent, RDF_TYPE)).toEqual([PROV + 'SoftwareAgent', SCHEMA + 'SoftwareApplication']);
    expect([one(agent, SCHEMA + 'name'), one(agent, SCHEMA + 'softwareVersion')]).toEqual(['la-gram', '9.9.9']);
    expect([values(ada, RDF_TYPE), one(ada, SCHEMA + 'name')]).toEqual([[PROV + 'Person'], 'Ada']);
    // Read back for the panel, read-only.
    expect(provenanceOf(store, shop).changed).toEqual({ at: time(5), by: 'Ada', tool: 'la-gram 9.9.9' });
  });

  it('a shape moved or restyled is a change to its view; a name, to its element', () => {
    const model = app.session.modelIri!;
    const view = app.session.activeViewIri!;
    const shop = app.components.elementManager.createElement(`${AM4}ApplicationComponent`, model, { label: 'Web shop' }).value;
    app.components.viewManager.addElementToView(view, shop, { x: 10, y: 10, width: 120, height: 55 });
    const shopChanged = one(shop, DCT + 'modified');
    tick(60);
    app.components.viewManager.updateNodeBounds(view, shop, { x: 200, y: 10, width: 120, height: 55 });
    expect(one(view, DCT + 'modified')).toBe(time(60));
    expect(one(shop, DCT + 'modified')).toBe(shopChanged);
    tick(60);
    const node = store.getQuads(null, nn(NAMESPACES['arch-vis'] + 'archElement'), nn(shop), defaultGraph() as never)[0]!.subject.value;
    app.components.viewManager.setAppearance(view, node, { fillColor: '#ffcc00' });
    expect(one(view, DCT + 'modified')).toBe(time(120));
    expect(one(shop, DCT + 'modified')).toBe(shopChanged);
    tick(60);
    app.components.elementManager.updateProperty(shop, NAMESPACES.skos + 'prefLabel', literal('Shop front', 'en') as never);
    expect(one(shop, DCT + 'modified')).toBe(time(180));
  });

  it('is part of the edit: undo takes the stamps back with it, redo puts them again', () => {
    const model = app.session.modelIri!;
    const model_ = () => snapshotOf(store.getQuads(null, null, null, defaultGraph() as never));
    const before = model_();
    const recorded = store.record(() =>
      app.components.elementManager.createElement(`${AM4}BusinessActor`, model, { label: 'Clerk' }).value,
    );
    expect(recorded.added.some((q) => q.predicate.value === PROV + 'wasGeneratedBy')).toBe(true);
    store.applyDiff(recorded, true);
    expect(model_()).toEqual(before);
    store.applyDiff(recorded);
    expect(one(recorded.result, PROV + 'wasGeneratedBy')).toBeDefined();
  });

  it('one activity a session: saving ends it; one nothing names any more goes, and so does a user nobody is', () => {
    const ns = app.session.namespace()!.namespace;
    const model = app.session.modelIri!;
    const shop = app.components.elementManager.createElement(`${AM4}ApplicationComponent`, model, { label: 'Web shop' }).value;
    const view = app.session.activeViewIri!;
    const first = one(shop, PROV + 'wasGeneratedBy')!;
    app.components.eventBus.emit('model-saved', {});
    provenance.endActivity();
    editor = { name: 'Grace', email: 'Grace@Example.com' };
    tick(3600);
    // Everything the first activity generated changes in the second: it goes, and Ada with it.
    for (const iri of [shop, view, model]) app.components.elementManager.updateProperty(iri, NAMESPACES.skos + 'definition', literal('x', 'en') as never);
    const second = one(shop, PROV + 'wasGeneratedBy')!;
    expect(second).toBe(`${ns}provenance/edit-activity-2`);
    expect(store.getQuads(nn(first), null, null, defaultGraph() as never)).toEqual([]);
    expect(store.getQuads(nn(`${ns}provenance/user-${keyDigest('Ada')}`), null, null, defaultGraph() as never)).toEqual([]);
    // Grace by her address, lower-cased: one user whatever the case she types it in.
    const grace = `${ns}provenance/user-${keyDigest('grace@example.com')}`;
    expect(values(second, PROV + 'wasAssociatedWith')).toContain(grace);
    expect([one(grace, SCHEMA + 'name'), one(grace, SCHEMA + 'email')]).toEqual(['Grace', 'Grace@Example.com']);
    // la-gram 9.9.9 is still named by the second.
    expect(values(modellerIri('9.9.9'), RDF_TYPE)).toHaveLength(2);
  });

  it('a user with a Git account: named by the account, whatever their name or address; what is known of them now replaces what was', () => {
    const ns = app.session.namespace()!.namespace;
    const model = app.session.modelIri!;
    editor = { name: 'Ada', account: { url: 'https://gitlab.com/ada', username: 'ada' } };
    const shop = app.components.elementManager.createElement(`${AM4}ApplicationComponent`, model, { label: 'Web shop' }).value;
    const user = `${ns}provenance/user-${keyDigest('https://gitlab.com/ada')}`;
    expect(values(one(shop, PROV + 'wasGeneratedBy')!, PROV + 'wasAssociatedWith')).toContain(user);
    expect([one(user, SCHEMA + 'name'), one(user, SCHEMA + 'sameAs'), one(user, SCHEMA + 'alternateName'), one(user, SCHEMA + 'email')])
      .toEqual(['Ada', 'https://gitlab.com/ada', 'ada', undefined]);
    expect(provenanceOf(store, shop).changed).toMatchObject({ by: 'Ada', account: 'https://gitlab.com/ada' });
    // Another session, the name corrected and an address given: the same user, told what is known now.
    provenance.endActivity();
    editor = { name: 'Ada Lovelace', email: 'ada@example.org', account: { url: 'https://gitlab.com/ada', username: 'ada' } };
    tick(60);
    app.components.elementManager.updateProperty(shop, NAMESPACES.skos + 'definition', literal('x', 'en') as never);
    expect(values(user, SCHEMA + 'name')).toEqual(['Ada Lovelace']);
    expect(values(user, SCHEMA + 'email')).toEqual(['ada@example.org']);
    expect(values(user, RDF_TYPE)).toEqual([PROV + 'Person']);
  });

  it('not an edit: what runs without stamps, and a collaborator’s change; a value set by hand stays', () => {
    const model = app.session.modelIri!;
    const shop = app.components.elementManager.createElement(`${AM4}ApplicationComponent`, model, { label: 'Web shop' }).value;
    const stamped = one(shop, DCT + 'modified');
    tick(10);
    app.withoutStamps(() => app.components.elementManager.updateProperty(shop, NAMESPACES.skos + 'definition', literal('a', 'en') as never));
    store.withOrigin('remote', () => app.components.elementManager.updateProperty(shop, NAMESPACES.skos + 'note', literal('b', 'en') as never));
    expect(one(shop, DCT + 'modified')).toBe(stamped);
    tick(10);
    store.batch(() => {
      app.components.elementManager.updateProperty(shop, NAMESPACES.skos + 'definition', literal('c', 'en') as never);
      app.components.elementManager.updateProperty(shop, DCT + 'modified', literal('2020-01-01T00:00:00Z', namedNode(NAMESPACES.xsd + 'dateTime')) as never);
    });
    expect(one(shop, DCT + 'modified')).toBe('2020-01-01T00:00:00Z');
    expect(one(shop, PROV + 'generatedAtTime')).toBe(time(20));
  });

  it('a deleted concept takes its stamps with it; what pointed at it, and the model, are changed', () => {
    const model = app.session.modelIri!;
    const shop = app.components.elementManager.createElement(`${AM4}ApplicationComponent`, model, { label: 'Web shop' }).value;
    tick(30);
    app.components.elementManager.deleteElement(shop);
    expect(store.getQuads(nn(shop), null, null, defaultGraph() as never)).toEqual([]);
    expect(one(model, DCT + 'modified')).toBe(time(30));
  });

  it('opening is no edit: the file is as it was written, and the next change is stamped', async () => {
    const saved = app.saveModel('trig');
    const quads = () => store.getQuads(null, null, null, defaultGraph() as never).length;
    await app.openModel(saved.text, saved.fileName);
    const opened = quads();
    expect(app.saveModel('trig').text).toBe(saved.text);
    expect(quads()).toBe(opened);
  });
});

describe('saved: the provenance graph', () => {
  beforeEach(async () => {
    await freshApp();
    app.newModel('Shop');
  }, 60_000);

  it('TriG holds the PROV statements in {ns}graph/provenance, the dates with the concept; the RDF panel can leave them out', () => {
    const model = app.session.modelIri!;
    app.components.elementManager.createElement(`${AM4}ApplicationComponent`, model, { label: 'Web shop' });
    const trig = app.saveModel('trig').text;
    const provenanceGraph = trig.slice(trig.indexOf('mg:provenance {'));
    expect(provenanceGraph).toContain('prov:wasGeneratedBy mp:edit-activity-1');
    expect(provenanceGraph).toContain(`mp:user-${keyDigest('Ada')} a prov:Person`);
    expect(provenanceGraph).toContain('a prov:Activity');
    expect(provenanceGraph).toContain('<https://app.linked.archi/la-gram/v9.9.9> a prov:SoftwareAgent');
    expect(provenanceGraph.slice(0, provenanceGraph.indexOf('}'))).not.toContain('dcterms:modified');
    const semantic = trig.slice(trig.indexOf('mg:semantic {'), trig.indexOf('}', trig.indexOf('mg:semantic {')));
    expect(semantic).toContain('dcterms:modified');
    expect(semantic).not.toContain('prov:');
    // Without provenance: no PROV statement, the dates stay.
    const without = app.saveModel('trig', 'full', { provenance: false }).text;
    expect(without).not.toContain('mg:provenance');
    expect(without).not.toMatch(/prov:\w+ /);
    expect(without).toContain('dcterms:modified');
  });
});

describe('merged: the later edit', () => {
  it('a concept both sides changed keeps the activity that ended later; the other goes, with whom only it named', () => {
    const ns = 'https://example.org/shop/';
    const line = (s: string, p: string, o: string) => `<${s}> <${p}> ${o} .`;
    const iri = (i: string) => `<${i}>`;
    const at = (t: string) => `"${t}"^^<${NAMESPACES.xsd}dateTime>`;
    const shop = `${ns}element/shop`;
    const [a, b, ada, grace, agent] = [`${ns}provenance/a`, `${ns}provenance/b`, `${ns}provenance/ada`, `${ns}provenance/grace`, modellerIri('1.0.0')];
    const activity = (act: string, person: string, ended: string) => [
      line(act, RDF_TYPE, iri(PROV + 'Activity')),
      line(act, PROV + 'endedAtTime', at(ended)),
      line(act, PROV + 'wasAssociatedWith', iri(agent)),
      line(act, PROV + 'wasAssociatedWith', iri(person)),
    ];
    const merged = settleEditProvenance([
      line(shop, PROV + 'wasGeneratedBy', iri(a)),
      line(shop, PROV + 'wasGeneratedBy', iri(b)),
      ...activity(a, ada, '2026-11-20T10:00:00Z'),
      ...activity(b, grace, '2026-11-20T11:00:00Z'),
      line(ada, RDF_TYPE, iri(PROV + 'Person')),
      line(grace, RDF_TYPE, iri(PROV + 'Person')),
      line(agent, RDF_TYPE, iri(PROV + 'SoftwareAgent')),
    ]);
    expect(merged.filter((l) => l.includes('wasGeneratedBy'))).toEqual([line(shop, PROV + 'wasGeneratedBy', iri(b))]);
    expect(merged.some((l) => l.startsWith(iri(a)) || l.startsWith(iri(ada)))).toBe(false);
    expect(merged.some((l) => l.startsWith(iri(grace)))).toBe(true);
    expect(merged.some((l) => l.startsWith(iri(agent)))).toBe(true);
  });
});

