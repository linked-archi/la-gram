/**
 * Custom event detail for palette drag operations.
 *
 * Emitted when the user presses on, or clicks, an element or relationship type.
 *
 * `sourceEvent` is the whole reason this is an event rather than a notification.
 * The listener hands it to diagram-js's `create` service, and `Dragging.init`
 * seeds the entire gesture from it: the start point, whether the drag is touch,
 * and the `stopPropagation` that keeps the press from also selecting text. Handed
 * nothing, `create.start` arms a drag anchored at the origin.
 */
export interface PaletteDragDetail {
  /** IRI of the type being dragged. */
  iri: string;
  /** Display label. */
  label: string;
  /** Whether this is an element or relationship type. */
  kind: 'element' | 'relationship';
  /** The raw `mousedown` or `click` that started the gesture. */
  sourceEvent: MouseEvent;
}

/**
 * Emitted when the user picks a different classification axis in the
 * "Group by" selector. The palette itself is regenerated by whoever owns the
 * PaletteGenerator — the panel only reports the choice.
 */
export interface PaletteAxisChangeDetail {
  /** IRI of the axis to group by. */
  axisIri: string;
}

/** Case-insensitive substring match, used by the search box. */
function matches(text: string | undefined, query: string): boolean {
  if (!query) return true;
  return (text ?? '').toLowerCase().includes(query);
}

/**
 * Palette panel Lit component — the app's one and only palette.
 *
 * Displays element types grouped by category and relationship types from a
 * PaletteDefinition, with a search box and a "Group by" axis selector. Supports
 * collapsible groups and drag-to-canvas for element creation.
 *
 * ## Why this owns the element types
 *
 * diagram-js's own in-canvas palette used to list them too, which put the same
 * 42 types on screen twice. bpmn-js gets away with a single in-canvas strip
 * because BPMN has about ten palette entries; a metamodel-driven tool does not —
 * ArchiMate 4.0 alone publishes 42 concrete types across 8 groups, and the next
 * metamodel will publish a different number. A sidebar has room to group, label
 * and search them; a narrow vertical strip inside the canvas does not, and has
 * nowhere to put the axis selector or the relationship list. So the in-canvas
 * palette is gone, its three global tools moved to `canvas-toolbar`, and this is
 * the only palette.
 *
 * ## Why the drag is `mousedown`, not HTML5 drag-and-drop
 *
 * The entries used to be `draggable="true"` and carry a JSON payload on
 * `dataTransfer`, with a `drop` listener on the canvas host translating client
 * coordinates by hand. That could never use diagram-js's `create` service — so no
 * drag preview, no snapping, and nothing a browser test could drive, because
 * Chrome fires `dragover`/`drop` and no `mousemove` once a native drag begins,
 * and `mousemove` is what diagram-js's `Dragging` listens on.
 *
 * Starting the gesture from `mousedown` instead hands the raw event to
 * `create.start`, and `Dragging` binds `mousemove`/`mouseup` on `document` — so a
 * press that starts out here in the sidebar is tracked all the way onto the
 * canvas, gets diagram-js's preview and snapping, and drops at a position
 * diagram-js computed itself. A drop that lands outside the canvas simply finds
 * no hover target and cancels, which is the correct outcome.
 *
 * `click` is wired to the same handler because `Create.start` calls
 * `dragging.init(..., { autoActivate: true })`. On a `click` the button is already
 * up, so the drag then follows the pointer until the *next* click — the
 * click-to-place gesture bpmn-js's palette offers. A plain press-and-release here
 * arms and immediately cancels the drag, and the `click` that follows arms it
 * again; a press-and-drag ends over the canvas, whose mouseup produces no `click`
 * on this item, so the two never both fire for one gesture.
 *
 * Viewpoint filtering can be handled in two ways:
 * 1. Externally — the parent passes an already-filtered PaletteDefinition.
 * 2. Internally — set the `activeViewpoint` property and the component
 *    filters the palette to only show permitted types.
 */
